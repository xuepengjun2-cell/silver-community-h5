function envFile(file) {
  try {
    const env = {};
    fs.readFileSync(file, "utf8").split(/\r?\n/).forEach(line => {
      const raw = line.trim();
      if (!raw || raw.startsWith("#") || !raw.includes("=")) return;
      const idx = raw.indexOf("=");
      let value = raw.slice(idx + 1).trim();
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
      env[raw.slice(0, idx).trim()] = value;
    });
    return env;
  } catch {
    return {};
  }
}

function parseDoc(v) {
  if (v == null || typeof v === "object") return v;
  try { return JSON.parse(v); } catch { return v; }
}

function lines(items) {
  return items.filter(Boolean).join("\n");
}

function uniq(items) {
  return [...new Set(items.filter(Boolean).map(x => String(x).trim()).filter(Boolean))];
}

function detectType(a) {
  const text = `${a.title || ""} ${a.category || ""} ${(a.tags || []).join(" ")}`;
  if (/美拍|拍照|摄影|街拍|影楼|形象|旗袍|肖像|合影/.test(text)) return "photo";
  if (/KTV|唱|歌|合唱|音乐|黑胶|非洲鼓|配音|朗诵|舞蹈|才艺/.test(text)) return "performance";
  if (/单身|红娘|老乡|社交|茶话|茶聚|饭局|家宴|麻将|掼蛋|生日|迎新|饭搭子|邻里|老友|朋友/.test(text)) return "social";
  if (/红酒|私房菜|烘焙|咖啡|香道|插花|园艺|花艺|茶|美学|香氛|穿搭/.test(text)) return "lifestyle";
  if (/博物馆|读书|非遗|扎染|国画|书法|数码|手机|收藏|文化|地方志|建筑/.test(text)) return "culture";
  if (/徒步|山|采摘|太极|温泉|健步|公园|露营|康养|养生|八段锦|睡眠|肩颈|健康|轻食|早餐/.test(text)) return "health";
  if (/门店|美容院|茶馆|餐厅|瑜伽馆|足疗|体验日|联名|联合/.test(text)) return "store";
  if (/9\.9|5元|低价|体验券|公益|唤醒|同行|1元|19元|29元/.test(text)) return "low";
  if (/家庭|亲子|夫妻|隔代|空巢|父母|沟通|带娃/.test(text)) return "family";
  if (/端午|中秋|重阳|冬至|新年|母亲节|七夕|春日|节|节气|赏花/.test(text)) return "festival";
  return "general";
}

