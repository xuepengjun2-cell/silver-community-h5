function enrichedIntro(activity) {
  const type = detectType(activity);
  const meta = typeMeta[type] || typeMeta.general;
  const base = String(activity.intro || "").trim();
  if (base && base.length >= 30) return base;
  return `${activity.title}面向${meta.persona}，通过${meta.value}，让客户在一次轻松、可参与、可沉淀素材的线下活动中建立信任，并自然承接后续活动、会员或相关产品。`;
}

function enrichedHighlights(activity) {
  const type = detectType(activity);
  const meta = typeMeta[type] || typeMeta.general;
  return uniq([...(activity.highlights || []).slice(0, 3), ...meta.highlights]).slice(0, 6);
}

function enrichedSchedule(activity) {
  const type = detectType(activity);
  const meta = typeMeta[type] || typeMeta.general;
  return meta.schedule.map(([time, item]) => ({ time, item }));
}

async function main() {
  const commit = process.argv.includes("--commit");
  const env = { ...envFile("/etc/silver-community.env"), ...process.env };
  const conn = await mysql.createConnection({
    host: env.DB_HOST || "127.0.0.1",
    port: Number(env.DB_PORT || 3306),
    user: env.DB_USER || "silver",
    password: env.DB_PASS || "",
    database: env.DB_NAME || "silver",
    charset: "utf8mb4"
  });
  const [rows] = await conn.query("SELECT id, doc FROM activities");
  const changed = [];
  for (const row of rows) {
    const doc = parseDoc(row.doc);
    if (!doc || typeof doc !== "object") continue;
    const next = {
      ...doc,
      intro: enrichedIntro(doc),
      highlights: enrichedHighlights(doc),
      schedule: enrichedSchedule(doc),
      plan: enrichedPlan(doc),
      updatedAt: new Date().toISOString()
    };
    changed.push({ id: row.id, title: next.title, category: next.category, type: detectType(next) });
    if (commit) {
      await conn.query(
        "UPDATE activities SET updated_at=?, doc=? WHERE id=?",
        [next.updatedAt, JSON.stringify(next), row.id]
      );
    }
  }
  await conn.end();
  const byType = changed.reduce((acc, item) => {
    acc[item.type] = (acc[item.type] || 0) + 1;
    return acc;
  }, {});
  console.log(JSON.stringify({ mode: commit ? "commit" : "dry-run", changed: changed.length, byType, samples: changed.slice(0, 12) }, null, 2));
}

main().catch(err => {
  console.error(err.stack || err);
  process.exit(1);
});
